"""CITES effectiveness intermediate regeneration — psycopg2 port (figs 1, 2).

Port of the earlier cites_effectiveness_export.py merge+scoring logic (not
part of this release), reading the `arctic` schema directly.

Field-level provenance (see visualizations/provenance/PROVENANCE.md):
- EXACT from DB: species columns, cites listings, latest IUCN, trade counts,
  wild-origin counts, period years, mode-purpose, total_quantity, CMS joins.
- TOP EXPORTERS: mode-exporter rule; 3 species have legacy tie-break values
  that differ (Eubalaena japonica, Hyperoodon ampullatus, Phoebastria
  albatrus) — documented divergence, values regenerated by the stated rule.
- FROZEN LEGACY (logic lost with the dropped article_summary_table):
  trade_trend + data_quality_score are read from
  visualizations/provenance/legacy_frozen_fields.csv (frozen from the
  committed 2025-09-13 JSON). Recomputing trade_trend is a domain call for
  the authors. has_cms_action_plan was constant False.
- DIVERGENT BY VINTAGE: catch aggregates (the frozen JSON predates the
  2025-06-11 NAMMCO reload; e.g. narwhal 121 vs live 133 records).

The figure scripts consume only: scientific_name, common_name, iucn_status,
cites_appendix, trade_records_count, wild_origin_count,
most_recorded_trade_use, trade_trend — all exact or frozen-legacy.
"""
import csv
import json
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from pg_common import query
from global_scope import latest_global

# The manuscript's corpus is arctic_v2. Three of these generators read the
# pre-rebuild `arctic` schema instead, which is why Figure 2 was titled
# "473,102 trade records" while the manuscript reports 492,095. One name,
# overridable, so the figures and the claims cannot describe different data.
import os as _os


def _run_date() -> str:
    """The date this file was actually produced.

    These fields were hardcoded to "2026-07-22" and were still saying so on
    2026-08-15, in files regenerated minutes earlier from a different corpus.
    A provenance date that never moves is worse than an absent one: a reader
    has no reason to distrust it.

    V-29 strips these before comparing digests, so a live date does not make
    the intermediates look unreproducible.
    """
    import datetime as _dt
    return _dt.date.today().isoformat()
SCHEMA = _os.environ.get("ARCTIC_SCHEMA", "arctic_v2")

ROOT = Path(__file__).parent.parent.parent
OUT = ROOT / "data/raw/1_DATA_cites_effectiveness.json"
LEGACY = ROOT / "visualizations/provenance/legacy_frozen_fields.csv"

ARCTIC_STATES = {"CA", "US", "RU", "NO", "IS", "DK", "SE", "FI", "GL"}


def mode_or_none(series):
    s = series.dropna()
    s = s[s != ""]
    return s.mode().iloc[0] if len(s) else None


def build():
    species = pd.DataFrame(query(f"SELECT * FROM {SCHEMA}.species"))
    cites = pd.DataFrame(query(f"SELECT * FROM {SCHEMA}.cites_listings"))
    iucn = pd.DataFrame(query(f"SELECT * FROM {SCHEMA}.iucn_assessments"))
    cms = pd.DataFrame(query(f"SELECT * FROM {SCHEMA}.cms_listings"))
    catch = pd.DataFrame(query(f"SELECT species_id, year, catch_total, quota, country_id FROM {SCHEMA}.catch_records"))
    trade = pd.DataFrame(query(f"""SELECT species_id, year, quantity, purpose, source, exporter
                                  FROM {SCHEMA}.cites_trade_records"""))

    legacy = {r["scientific_name"]: r for r in csv.DictReader(open(LEGACY))}

    result = species.copy()

    # CITES current listing + history
    if len(cites):
        cur = cites[cites["is_current"] == True].groupby("species_id").agg(
            {"appendix": "first", "listing_date": "first"}).reset_index()
        cur.columns = ["id", "cites_appendix", "cites_listing_date"]
        result = result.merge(cur, on="id", how="left")
        hist = cites.groupby("species_id").agg({"listing_date": ["min", "count"]}).reset_index()
        hist.columns = ["id", "first_cites_listing", "appendix_changes"]
        result = result.merge(hist, on="id", how="left")

    # Latest GLOBAL IUCN. The year sort alone picks a EUROPEAN assessment for
    # twenty-one of the forty-three focal species - the fin whale's 2023
    # Europe assessment and its 2018 global assessment have different
    # categories - and this frame feeds the figures that then
    # draw a regional category as the species' status. The paper's own rule is
    # global assessments only. See global_scope.py for the measurement.
    if len(iucn):
        latest = latest_global(iucn)
        latest = latest[["species_id", "status", "year_published"]]
        latest.columns = ["id", "iucn_status", "iucn_year"]
        result = result.merge(latest, on="id", how="left")

    # Trade summary — reconstructed from cites_trade_records (see docstring)
    if len(trade):
        rows = []
        for sid, g in trade.groupby("species_id"):
            years = g["year"].dropna()
            rows.append({
                "id": sid,
                "trade_records_count": len(g),
                "total_quantity": float(g["quantity"].dropna().sum()) if g["quantity"].notna().any() else None,
                "most_recorded_trade_use": mode_or_none(g["purpose"]),
                "wild_origin_count": int((g["source"] == "W").sum()),
                "period_start_year": int(years.min()) if len(years) else None,
                "period_end_year": int(years.max()) if len(years) else None,
                "top_arctic_exporter": mode_or_none(g[g["exporter"].isin(ARCTIC_STATES)]["exporter"]),
                "top_global_exporter": mode_or_none(g["exporter"]),
            })
        result = result.merge(pd.DataFrame(rows), on="id", how="left")

    # Frozen legacy fields (lost article_summary_table logic)
    result["trade_trend"] = result["scientific_name"].map(
        lambda n: legacy.get(n, {}).get("trade_trend"))
    result["data_quality_score"] = result["scientific_name"].map(
        lambda n: float(legacy[n]["data_quality_score"]) if n in legacy and legacy[n]["data_quality_score"] not in ("", None) else None)
    result["has_cms_action_plan"] = result["scientific_name"].map(
        lambda n: legacy.get(n, {}).get("has_cms_action_plan") == "True")

    # CMS
    if len(cms):
        cms_s = cms.groupby("species_id").agg({
            "appendix": lambda x: ", ".join(sorted({str(v) for v in x})),
            "agreement": lambda x: ", ".join(sorted({str(v) for v in x if v})) or None,
            "listing_date": "min",
        }).reset_index()
        cms_s.columns = ["id", "cms_appendices", "cms_agreements", "cms_first_listing"]
        result = result.merge(cms_s, on="id", how="left")

    # Catch (documented vintage divergence vs the frozen JSON)
    if len(catch):
        cs = catch.groupby("species_id").agg({
            "catch_total": ["sum", "mean", "count"],
            "year": ["min", "max"],
            "country_id": "nunique",
        }).reset_index()
        cs.columns = ["id", "total_catch", "avg_catch", "catch_records",
                      "first_catch_year", "last_catch_year", "harvest_countries"]
        result = result.merge(cs, on="id", how="left")

    # ---- scoring, verbatim from the original ----
    df = result
    df["effectiveness_score"] = 0
    # population_trend was free prose (43 values, mean 430 characters) in the
    # pre-rebuild schema, so this map never matched a key and fillna gave every
    # species the same 15 points. arctic_v2 does not carry the column at all.
    # Rather than fabricate a constant, the component is recorded as absent and
    # the score's stated range shrinks to match. The manuscript disclaims a
    # composite effectiveness score, so nothing published depends on this.
    HAS_TREND = ("population_trend" in df.columns and df["population_trend"].isin(
        ["increasing", "stable", "unknown", "decreasing"]).any())
    if HAS_TREND:
        df["population_score"] = df["population_trend"].map(
            {"increasing": 30, "stable": 25, "unknown": 15, "decreasing": 0}).fillna(15)
        df["effectiveness_score"] += df["population_score"]
    else:
        df["population_score"] = None
    df["trade_trend_score"] = df["trade_trend"].map(
        {"decreasing": 30, "stable": 20, "increasing": 0}).fillna(10)
    df["effectiveness_score"] += df["trade_trend_score"]
    df["iucn_score"] = df["iucn_status"].map(
        {"LC": 20, "NT": 15, "VU": 10, "EN": 5, "CR": 0, "EW": 0, "EX": 0}).fillna(10)
    df["effectiveness_score"] += df["iucn_score"]

    def cites_score(row):
        if pd.isna(row["cites_appendix"]):
            return 5
        if row["iucn_status"] in ["CR", "EN"] and row["cites_appendix"] == "I":
            return 10
        elif row["iucn_status"] in ["VU", "NT"] and row["cites_appendix"] == "II":
            return 10
        elif row["iucn_status"] == "LC" and row["cites_appendix"] == "III":
            return 10
        return 5

    df["cites_score"] = df.apply(cites_score, axis=1)
    df["effectiveness_score"] += df["cites_score"]
    df["data_quality_bonus"] = (df["data_quality_score"] / 10).fillna(5)
    df["effectiveness_score"] += df["data_quality_bonus"]

    def categorize(score):
        return ("High Success" if score >= 80 else "Moderate Success" if score >= 60
                else "Limited Success" if score >= 40 else "Needs Improvement")

    df["effectiveness_category"] = df["effectiveness_score"].apply(categorize)

    def priority(row):
        # Guarded for the same reason as population_score: against free prose
        # this equality was never true, so "Critical" was unreachable for all 43
        # species. Testing an absent signal silently is worse than not testing it.
        if HAS_TREND and row["population_trend"] == "decreasing" \
                and row["trade_trend"] == "increasing":
            return "Critical"
        elif row["effectiveness_score"] < 40:
            return "High"
        elif row["effectiveness_score"] < 60:
            return "Medium"
        return "Low"

    df["conservation_priority"] = df.apply(priority, axis=1)
    return df


def clean(obj):
    if isinstance(obj, dict):
        return {k: clean(v) for k, v in obj.items() if v is not None}
    if isinstance(obj, list):
        return [clean(i) for i in obj if i is not None]
    if isinstance(obj, float):
        return None if pd.isna(obj) else obj
    if hasattr(obj, "item"):
        return obj.item()
    return obj


def main():
    df = build()
    out = {
        "metadata": {
            "analysis_date": _run_date() + "T00:00:00",
            "total_species": len(df),
            "data_sources": ["species", "cites_listings", "iucn_assessments",
                             "cites_trade_records", "cms_listings", "catch_records"],
        },
        "summary_statistics": {
            "total_species": len(df),
            "species_with_cites": int(df["cites_appendix"].notna().sum()),
            "species_with_trade": int((df["trade_records_count"].notna() & (df["trade_records_count"] > 0)).sum()),
            "effectiveness_distribution": df["effectiveness_category"].value_counts().to_dict(),
            "priority_distribution": df["conservation_priority"].value_counts().to_dict(),
            "average_effectiveness_score": float(df["effectiveness_score"].mean()),
            "appendix_distribution": df["cites_appendix"].value_counts().to_dict(),
            # Counting a free-prose column yields 43 groups of one, which is
            # noise dressed as a distribution.
            "population_trends": (
                df["population_trend"].value_counts().to_dict()
                if "population_trend" in df.columns
                and df["population_trend"].isin(
                    ["increasing", "stable", "unknown", "decreasing"]).any()
                else None),
            "trade_trends": df["trade_trend"].value_counts().to_dict(),
        },
        "species_analyses": df.to_dict("records"),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(clean(out), f, indent=2, default=str, sort_keys=True)
    print(f"effectiveness: {len(df)} species -> {OUT}")


if __name__ == "__main__":
    main()
