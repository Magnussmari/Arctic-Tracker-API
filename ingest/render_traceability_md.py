"""Render the Results-traceability supplementary table from the deposited CSV.

WHY THIS EXISTS
---------------
The table was generated straight from the database alongside the CSV. When the
CSV was later corrected - three trajectory claims answered from the deposit
rather than left pending - the published Markdown kept saying PENDING, because
regenerating it needed credentials nobody had to hand. Two writers, one
artefact, and the one a reviewer reads was the stale one.

So the chain is now single: the deposit holds the data, the CSV holds the
values, the CSV is verified against the deposit by
deposit/verification/verify_claims_offline.py, and this renders the table a
reviewer reads. No step needs a database, which is the same standard the paper
asks of its own results.

Usage: python ingest/render_traceability_md.py   (then the gate re-runs)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
SRC = ROOT / "deposit/results_traceability.csv"
OUT = ROOT / "deposit/results_traceability.md"

HEADER = ("<!-- GENERATED by ingest/render_traceability_md.py from "
          "deposit/results_traceability.csv. Do not edit: the next render "
          "overwrites it. Edit the CSV's generator instead. -->")

PREAMBLE = (
    "Every quantitative claim in the paper, its operative definition, the table "
    "it comes from, and the query or computation that reproduces it against the "
    "deposited corpus.",
    "",
    "Every claim listed here is valued, and every one is reproducible from the "
    "deposited package alone - no database, credentials or network access. "
    "`deposit/verification/verify_claims_offline.py` recomputes each value under "
    "the operative definition recorded beside it and fails if any differs.",
)


def main() -> int:
    if not SRC.exists():
        print(f"UNMEASURED: {SRC} is not here.", file=sys.stderr)
        return 3
    rows = list(csv.DictReader(open(SRC)))

    blank = [r["claim_id"] for r in rows if not r["value"].strip()
             or "PENDING" in r["value"]]
    if blank:
        print(f"{', '.join(blank)} carry no value. The table states that every "
              f"claim is reproducible, so rendering it now would publish a "
              f"sentence the table itself contradicts.", file=sys.stderr)
        return 1

    lines = [HEADER, "", "# Supplementary Table: Results traceability", "",
             *PREAMBLE, "",
             "| ID | Claim | Value | Methods | Source table | Operative definition |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['claim_id']} | {r['claim']} | **{r['value']}** | "
                     f"{r['methods_section']} | `{r['source_table']}` | "
                     f"{r['operative_definition']} |")
    lines += ["", "## Queries", ""]
    for r in rows:
        if r["query"].strip():
            q = r["query"].strip()
            body = f"```sql\n{q}\n```" if "select" in q.lower() else f"`{q}`"
            lines.append(f"**{r['claim_id']}**\n\n{body}\n")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} - {len(rows)} claims, every one valued.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
